export function getCourseBoardPosts(courseId: string): CourseBoardPost[] {
  return courseBoardPosts[courseId] ?? [];
}

export function getRecentBoardPosts(
  posts: CourseBoardPost[],
  limit = 5,
): CourseBoardPost[] {
  return [...posts]
    .sort((a, b) => b.createdAt.localeCompare(a.createdAt))
    .slice(0, limit);
}
